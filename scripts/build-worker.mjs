// Produce Sites' single ESM Worker from the Rust crate and the dashboard assets.
// Binaryen AOT avoids dynamic WebAssembly compilation inside a Worker isolate.
import { spawnSync } from "node:child_process";
import { createHash } from "node:crypto";
import { mkdtempSync, mkdirSync, readFileSync, readdirSync, copyFileSync, writeFileSync,
  unlinkSync, rmdirSync, existsSync, renameSync } from "node:fs";
import { tmpdir } from "node:os";
import path from "node:path";
import { fileURLToPath } from "node:url";

const root = fileURLToPath(new URL("../", import.meta.url));
const temp = mkdtempSync(path.join(tmpdir(), "ttk-worker-"));
const lowered = path.join(temp, "lowered.wasm");
const core = path.join(temp, "core.mjs");
function run(program, args) {
  const proc = spawnSync(program, args, { cwd: root, encoding: "utf8", windowsHide: true, maxBuffer: 50 * 1024 * 1024 });
  if (proc.error) throw proc.error;
  if (proc.status !== 0) {
    const lines = (proc.stderr || proc.stdout || "").split(/\r?\n/).filter(Boolean);
    throw new Error(`${path.basename(args[0] || program)} exited ${proc.status}: ${lines.slice(0,4).map(s=>s.slice(0,240)).join("\n")}`);
  }
  return proc.stdout;
}
function tool(name, args) {
  return run(process.execPath, [path.join(root, "node_modules/binaryen/bin", name), ...args]);
}

try {
  const messages = run(process.env.CARGO || "cargo", ["build", "--locked", "--release", "--lib",
    "--target", "wasm32-unknown-unknown", "--message-format=json-render-diagnostics"]);
  const artifact = messages.trim().split(/\r?\n/).map(l=>JSON.parse(l))
    .find(m => m.reason === "compiler-artifact" && m.target?.name === "ttk_dashboard_site" && m.filenames?.some(n => n.endsWith(".wasm")));
  if (!artifact) throw new Error("Cargo did not report the dashboard WebAssembly artifact");
  const wasm = artifact.filenames.find(n=>n.endsWith(".wasm"));
  const binary = new WebAssembly.Module(readFileSync(wasm));
  for (const name of ["memory","reserve","server_run","output"]) {
    if (!WebAssembly.Module.exports(binary).some(e=>e.name === name)) throw new Error("Missing Rust export: " + name);
  }
  if (WebAssembly.Module.imports(binary).length) throw new Error("The Rust worker must have a standalone host ABI");
  // wasm2js needs LLVM's saturating float conversions lowered before its own i64 pass.
  tool("wasm-opt", [wasm, "--all-features","--llvm-nontrapping-fptoint-lowering","-o",lowered]);
  tool("wasm2js", [lowered, "--enable-bulk-memory","--enable-sign-ext","-O1","-o",core]);
  const compiled = readFileSync(core,"utf8");
  if (/^import\s/m.test(compiled)) throw new Error("Unexpected external import in generated AOT core");
  const types = {".html":"text/html; charset=utf-8",".css":"text/css; charset=utf-8",".js":"text/javascript; charset=utf-8",
    ".svg":"image/svg+xml",".woff2":"font/woff2",".png":"image/png",".ico":"image/x-icon",".txt":"text/plain; charset=utf-8"};
  const names = ["index.html","browser.js","app.css",...readdirSync(path.join(root,"dist/assets")).sort().map(n=>"assets/"+n)];
  const assets = {};
  for (const name of names) {
    const type = types[path.extname(name)];
    if (!type) throw new Error("Unexpected client asset: " + name);
    const buffer=readFileSync(path.join(root,"dist",name));
    assets["/"+name]={type, data:buffer.toString("base64"), etag:'"'+createHash("sha256").update(buffer).digest("hex")+'"'};
  }
  const adapter = readFileSync(path.join(root, "worker/adapter.mjs"),"utf8");
  const entry = readFileSync(path.join(root,"worker/entry.mjs"),"utf8");
  const dest=path.join(root, "dist/server/index.js");
  mkdirSync(path.dirname(dest),{recursive:true});
  const combined = [
    "// Generated by scripts/build-worker.mjs from the locked Rust build. Edit the Rust sources or worker/.",
    compiled,adapter,"const publicAssets = "+JSON.stringify(assets)+";",entry
  ].join("\n");
  writeFileSync(dest+".new",combined);
  renameSync(dest+".new",dest);
  copyFileSync(wasm,path.join(root,"dist/dashboard.wasm"));
  console.log("Built Rust Sites Worker ("+Buffer.byteLength(combined)+" bytes, "+names.length+" static assets)");
} finally {
  for (const file of [lowered,core]) if (existsSync(file)) unlinkSync(file);
  rmdirSync(temp);
}

