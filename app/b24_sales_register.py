"""Лиды и сделки Битрикс24 в реестре панели «Метрики → Отдел продаж» (источник — таблица crm_deals, открытые записи).

Сделка, которая уже есть в реестре из 1С, второй раз не создаётся:
  название вида «Т822-…» — тендер 1С Т-000822: он остаётся объектом, а если этап у него пуст, берётся этап сделки;
  номер заказа клиента в названии («00ЦБ-000813») — заказ 1С уже объект реестра.
Этап ставится по стадии Битрикса только там, где соответствие однозначно (STAGE_MAP); остальные стадии — этап выбирает
руководитель, при следующих обновлениях он не меняется. Закрытые в Битриксе записи в crm_deals не попадают: объект
реестра, которого больше нет среди открытых, закрывается («Закрыто без результата»).
"""
import re

TENDER_CATS = {"Поиск тендеров", "Договорная работа (тендеры)"}
# (воронка, стадия) → этап реестра; все стадии воронки лидов — «Лиды», кроме перечисленных
STAGE_MAP = {
    ("Отдел продаж", "Выявление потребности"): "Запрос",
    ("Отдел продаж", "Обработка отделами снабжения и логистики"): "Расчёт",
    ("Отдел продаж", "Подготовка КП"): "КП",
    ("Отдел продаж", "КП отправлено клиенту"): "КП",
    ("Отдел продаж", "Поставка продукции"): "Исполнение",
    ("Отдел продаж", "Дебиторская задолженность"): "Приёмка и оплата",
    ("Поиск тендеров", "Подача на площадке"): "Подача",
    ("Поиск тендеров", "Ожидает результатов"): "Результат",
    ("Поиск тендеров", "Разъяснение от заказчика"): "Дозапрос",
    ("Договорная работа (тендеры)", "Подготовка документов для подписания"): "Договор",
    ("Договорная работа (тендеры)", "В отгрузке и доставке"): "Исполнение",
    ("Договорная работа (тендеры)", "Закрывающие документы"): "Приёмка и оплата",
    ("Договорная работа (тендеры)", "Ожидает оплаты"): "Приёмка и оплата",
    ("Преддоговорная работа", "Договор подготовлен"): "Договор",
    ("Лиды", "Запросили ТКП"): "Запрос",
}
EXEC_STAGES = {"Передача в исполнение", "Исполнение", "Приёмка и оплата"}
ORDER_NO = re.compile(r"\d{2}[А-ЯЁ]{2}-\d{6}")
TENDER_NO = re.compile(r"^\s*[тТ]\s*-?\s*(\d+)")


def from_bitrix(con):
    """Строки реестра из открытых лидов и сделок Битрикс24 (crm_deals)."""
    known = {r[0] for r in con.execute("SELECT id FROM sales_objects WHERE source IN ('order', 'tender')")}
    logins = {r[0] for r in con.execute("SELECT login FROM employees")}
    out = []
    for r in con.execute("SELECT * FROM crm_deals WHERE COALESCE(semantic, 'P') NOT IN ('S', 'F')"):
        lead = (r["entity"] or "deal") == "lead"
        title = r["title"] or ""
        bid = re.sub(r"^(deal|lead)", "", r["id"])
        funnel = "Лиды" if lead else (r["category"] or "")
        match = None
        if not lead:
            order = ORDER_NO.search(title)
            if order and order.group(0) in known:
                continue  # заказ 1С уже объект реестра
            tn = TENDER_NO.match(title)
            if tn and "Т-%06d" % int(tn.group(1)) in known:
                match = "Т-%06d" % int(tn.group(1))
        stage = STAGE_MAP.get((funnel, r["stage"])) or ("Лиды" if lead else None)
        out.append({"key": r["id"], "source": "b24_lead" if lead else "b24_deal", "by": "Битрикс24", "match": match,
                    "id": ("Б24-Л-" if lead else "Б24-С-") + bid,
                    "type": "Лид" if lead else ("Исполнение" if stage in EXEC_STAGES else "Сделка"),
                    "channel": "Тендеры" if funnel in TENDER_CATS else "Прямые", "client": r["client"] or title,
                    "emp": r["emp"] if r["emp"] in logins else None, "status_1c": r["stage"], "amount": r["amount"] or None,
                    "entered": (r["created"] or "")[:16] or None, "stage": stage, "order_1c": None})
    return out
